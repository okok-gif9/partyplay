-- Truth-or-Dare prompts and room-local host-authored prompts are never accepted from game clients.
create table if not exists public.pp_truth_dare_prompts (
  id bigint generated by default as identity primary key,
  room_id uuid references public.pp_rooms(id) on delete cascade,
  choice text not null check (choice in ('truth','dare')),
  category text not null check (category in ('fun','friends','extreme','spicy')),
  text_fa text not null check (char_length(btrim(text_fa)) between 8 and 280),
  text_en text not null check (char_length(btrim(text_en)) between 8 and 280),
  created_by uuid references public.pp_profiles(id) on delete set null,
  is_builtin boolean not null default false,
  created_at timestamptz not null default now()
);
create index if not exists pp_truth_dare_prompts_room_category_idx on public.pp_truth_dare_prompts(room_id,category,choice);
alter table public.pp_truth_dare_prompts enable row level security;
revoke all on public.pp_truth_dare_prompts from public, anon, authenticated;

create table if not exists public.pp_truth_dare_round_results (
  session_id uuid not null references public.pp_game_sessions(id) on delete cascade,
  round_no integer not null check (round_no > 0),
  player_id uuid not null references public.pp_profiles(id) on delete cascade,
  choice text not null check (choice in ('truth','dare')),
  prompt_id bigint references public.pp_truth_dare_prompts(id) on delete set null,
  completed boolean not null default false,
  passed boolean not null default false,
  created_at timestamptz not null default now(),
  primary key(session_id,round_no)
);
create table if not exists public.pp_truth_dare_ratings (
  session_id uuid not null,
  round_no integer not null,
  rater_id uuid not null references public.pp_profiles(id) on delete cascade,
  score smallint not null check (score between 1 and 5),
  created_at timestamptz not null default now(),
  primary key(session_id,round_no,rater_id),
  foreign key(session_id,round_no) references public.pp_truth_dare_round_results(session_id,round_no) on delete cascade
);
alter table public.pp_truth_dare_round_results enable row level security;
alter table public.pp_truth_dare_ratings enable row level security;
revoke all on public.pp_truth_dare_round_results,public.pp_truth_dare_ratings from public,anon,authenticated;

create or replace function public.partyplay_truth_dare_prompt_safe(p_text text,p_strict boolean default true)
returns boolean language plpgsql immutable security invoker set search_path=public as $$
declare v_text text := lower(btrim(coalesce(p_text,'')));
begin
  if char_length(v_text)<8 or char_length(v_text)>280 then return false; end if;
  if v_text ~* '(sex|sexual|nude|naked|porn|drug|alcohol|weapon|suicide|self.?harm|password|passcode|credit.?card|phone.?number|address|stalk|harass|touch|blindfold|hurt|dangerous|threat|برهنه|رابطه جنسی|مواد مخدر|الکل|خودکشی|خودآزاری|رمز عبور|شماره تلفن|آدرس|تعقیب|آزار|لمس|آسیب|خطرناک)' then return false; end if;
  if p_strict and v_text ~* '(secret|private|phone|contact|social media|message a stranger|رازی که|خصوصی|مخاطبین|شبکه اجتماعی|شماره)' then return false; end if;
  return true;
end;
$$;

